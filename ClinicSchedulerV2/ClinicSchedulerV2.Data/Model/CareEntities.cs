using Microsoft.AspNetCore.Identity;

namespace ClinicSchedulerV2.Data.Model;

// Row classes for the tables added in 04-06. As with the original 17, they carry no rules:
// the constraints and triggers in db/postgres decide what is valid.

/// <summary>A login, belonging to exactly one employee or one patient (app_user).</summary>
public class AppUser : IdentityUser<int>
{
    public int? EmployeeId { get; set; }
    public Employee? Employee { get; set; }
    public int? PatientId { get; set; }
    public Patient? Patient { get; set; }
    public DateTime CreatedAt { get; set; }
}

public class Invoice
{
    public int InvoiceId { get; set; }
    public int PatientId { get; set; }
    public Patient Patient { get; set; } = null!;
    public InvoiceStatus Status { get; set; }
    public int CreatedBy { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateOnly? IssuedOn { get; set; }
    public DateOnly? DueOn { get; set; }
    public DateTime? VoidedAt { get; set; }
    public string? VoidReason { get; set; }
    public string? Notes { get; set; }
    public List<InvoiceLine> Lines { get; set; } = [];
    public List<Payment> Payments { get; set; } = [];
}

public class InvoiceLine
{
    public int LineId { get; set; }
    public int InvoiceId { get; set; }
    public int? AppointmentId { get; set; }
    public Appointment? Appointment { get; set; }
    public string Description { get; set; } = "";
    public string? BillingCode { get; set; }
    public short Quantity { get; set; } = 1;
    public decimal UnitPrice { get; set; }
    /// <summary>Generated by the database (quantity × unit price).</summary>
    public decimal Amount { get; set; }
}

public class Payment
{
    public int PaymentId { get; set; }
    public int InvoiceId { get; set; }
    public decimal Amount { get; set; }
    public PaymentMethod Method { get; set; }
    public string? Reference { get; set; }
    public DateTime PaidAt { get; set; }
    public int RecordedBy { get; set; }
    public Employee RecordedByEmployee { get; set; } = null!;
}

public class InsurancePolicy
{
    public int PolicyId { get; set; }
    public int PatientId { get; set; }
    public string PayerName { get; set; } = "";
    public string MemberId { get; set; } = "";
    public string? GroupNumber { get; set; }
    public bool IsPrimary { get; set; } = true;
    public DateOnly EffectiveFrom { get; set; }
    public DateOnly? EffectiveTo { get; set; }
    public bool IsActive { get; set; } = true;
}

public class WaitlistEntry
{
    public int EntryId { get; set; }
    public int PatientId { get; set; }
    public Patient Patient { get; set; } = null!;
    public int ServiceTypeId { get; set; }
    public ServiceType ServiceType { get; set; } = null!;
    public int? PreferredLocationId { get; set; }
    public Location? PreferredLocation { get; set; }
    public int? PreferredProviderId { get; set; }
    public Provider? PreferredProvider { get; set; }
    public DateOnly EarliestDate { get; set; }
    public DateOnly LatestDate { get; set; }
    public string? Notes { get; set; }
    public WaitlistStatus Status { get; set; }
    public int? AppointmentId { get; set; }
    public DateTime CreatedAt { get; set; }
}

public class VisitNote
{
    public int NoteId { get; set; }
    public int AppointmentId { get; set; }
    public Appointment Appointment { get; set; } = null!;
    public int AuthorId { get; set; }
    public Provider Author { get; set; } = null!;
    public string Body { get; set; } = "";
    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }
    public DateTime? SignedAt { get; set; }
}

public class Notification
{
    public int NotificationId { get; set; }
    public int? RecipientEmployeeId { get; set; }
    public int? RecipientPatientId { get; set; }
    public NotificationKind Kind { get; set; }
    public string Title { get; set; } = "";
    public string Body { get; set; } = "";
    public int? AppointmentId { get; set; }
    public int? InvoiceId { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime? ReadAt { get; set; }
}

// ---- Read-only rows from views -------------------------------------------------------------

/// <summary>vw_invoice_summary: totals, payments and balance, computed by the database.</summary>
public class InvoiceSummary
{
    public int InvoiceId { get; set; }
    public int PatientId { get; set; }
    public string Patient { get; set; } = "";
    public InvoiceStatus Status { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateOnly? IssuedOn { get; set; }
    public DateOnly? DueOn { get; set; }
    public decimal Total { get; set; }
    public decimal Paid { get; set; }
    public decimal Balance { get; set; }
    public bool IsOverdue { get; set; }
    public long LineCount { get; set; }
}

/// <summary>vw_patient_balance.</summary>
public class PatientBalance
{
    public int PatientId { get; set; }
    public string Patient { get; set; } = "";
    public decimal OpenBalance { get; set; }
    public decimal OverdueBalance { get; set; }
}

/// <summary>vw_superbill: one line per billed visit, with what an insurer needs.</summary>
public class SuperbillLine
{
    public int InvoiceId { get; set; }
    public int LineId { get; set; }
    public int PatientId { get; set; }
    public string Patient { get; set; } = "";
    public DateOnly DateOfBirth { get; set; }
    public string? PayerName { get; set; }
    public string? MemberId { get; set; }
    public string? GroupNumber { get; set; }
    public string Provider { get; set; } = "";
    public ProviderCredential Credential { get; set; }
    public string Npi { get; set; } = "";
    public DateOnly ServiceDate { get; set; }
    public string Service { get; set; } = "";
    public string? BillingCode { get; set; }
    public string Description { get; set; } = "";
    public short Quantity { get; set; }
    public decimal UnitPrice { get; set; }
    public decimal Amount { get; set; }
    public string Location { get; set; } = "";
    public string LocationAddress { get; set; } = "";
}
