-- =====================================================================
-- ClinicScheduler V2: Accounts
-- Apply after 01-03. Not part of the original MySQL design, which left
-- logins out of scope.
--
-- Contents
--   1. app_user and the ASP.NET Identity side tables (claims, logins,
--      tokens). Column names follow ASP.NET Core Identity, snake_cased.
--   2. Who is acting: current_user_id(), current_patient_id(), and
--      current_employee_id() redefined to fall back on the login
--   3. Account rules: one account per person, never for an inactive
--      person; deactivating a person locks their account
--   4. Patient scope: a session signed in as a patient may only request
--      appointments and cancellations for that patient, and may not
--      book, review or change anything directly
--   5. Audit: every audit_log row also records the login that acted
--
-- Trust model (unchanged from the original design): the application
-- tells the database who is acting with session settings,
--   SELECT set_config('app.current_user_id', '<app_user.id>', false);
-- and the triggers below act on that. Reads are scoped by the
-- application; the rules here govern writes.
-- =====================================================================

-- =====================================================================
-- 1. Tables
-- =====================================================================
CREATE TABLE app_user (
  id                     integer      GENERATED BY DEFAULT AS IDENTITY,
  employee_id            integer      NULL,
  patient_id             integer      NULL,
  user_name              varchar(256) NOT NULL,
  normalized_user_name   varchar(256) NOT NULL,
  email                  varchar(256) NULL,
  normalized_email       varchar(256) NULL,
  email_confirmed        boolean      NOT NULL DEFAULT FALSE,
  password_hash          text         NULL,
  security_stamp         text         NULL,
  concurrency_stamp      text         NULL,
  phone_number           text         NULL,
  phone_number_confirmed boolean      NOT NULL DEFAULT FALSE,
  two_factor_enabled     boolean      NOT NULL DEFAULT FALSE,
  lockout_end            timestamptz  NULL,
  lockout_enabled        boolean      NOT NULL DEFAULT TRUE,
  access_failed_count    integer      NOT NULL DEFAULT 0,
  created_at             timestamp    NOT NULL DEFAULT clinic_now(),
  CONSTRAINT pk_app_user PRIMARY KEY (id),
  CONSTRAINT uq_app_user_name UNIQUE (normalized_user_name),
  CONSTRAINT uq_app_user_email UNIQUE (normalized_email),
  CONSTRAINT uq_app_user_employee UNIQUE (employee_id),
  CONSTRAINT uq_app_user_patient UNIQUE (patient_id),
  CONSTRAINT fk_app_user_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id),
  CONSTRAINT fk_app_user_patient FOREIGN KEY (patient_id) REFERENCES patient (patient_id),
  -- Every account belongs to exactly one person: an employee or a patient
  CONSTRAINT ck_app_user_one_person CHECK (num_nonnulls(employee_id, patient_id) = 1),
  CONSTRAINT ck_app_user_failed_count CHECK (access_failed_count >= 0)
);

CREATE TABLE app_user_claim (
  id          integer GENERATED BY DEFAULT AS IDENTITY,
  user_id     integer NOT NULL,
  claim_type  text    NULL,
  claim_value text    NULL,
  CONSTRAINT pk_app_user_claim PRIMARY KEY (id),
  CONSTRAINT fk_app_user_claim_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX idx_app_user_claim_user ON app_user_claim (user_id);

CREATE TABLE app_user_login (
  login_provider        varchar(128) NOT NULL,
  provider_key          varchar(128) NOT NULL,
  provider_display_name text         NULL,
  user_id               integer      NOT NULL,
  CONSTRAINT pk_app_user_login PRIMARY KEY (login_provider, provider_key),
  CONSTRAINT fk_app_user_login_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);
CREATE INDEX idx_app_user_login_user ON app_user_login (user_id);

CREATE TABLE app_user_token (
  user_id        integer      NOT NULL,
  login_provider varchar(128) NOT NULL,
  name           varchar(128) NOT NULL,
  value          text         NULL,
  CONSTRAINT pk_app_user_token PRIMARY KEY (user_id, login_provider, name),
  CONSTRAINT fk_app_user_token_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

-- =====================================================================
-- 2. Who is acting
-- =====================================================================

-- The login making changes in this session, or NULL
CREATE FUNCTION current_user_id() RETURNS integer
LANGUAGE sql STABLE
AS $$ SELECT NULLIF(current_setting('app.current_user_id', true), '')::integer $$;

-- The patient this session is signed in as, or NULL for staff, providers and services
CREATE FUNCTION current_patient_id() RETURNS integer
LANGUAGE sql STABLE
AS $$ SELECT u.patient_id FROM app_user u WHERE u.id = current_user_id() $$;

-- The employee making changes: set directly by services without a login (the MCP
-- server), otherwise the employee behind the login. Same signature as before, so
-- every existing trigger picks this up.
CREATE OR REPLACE FUNCTION current_employee_id() RETURNS integer
LANGUAGE sql STABLE
AS $$
  SELECT COALESCE(
    NULLIF(current_setting('app.current_employee_id', true), '')::integer,
    (SELECT u.employee_id FROM app_user u WHERE u.id = current_user_id()))
$$;

-- =====================================================================
-- 3. Account rules
-- =====================================================================
CREATE FUNCTION trg_fn_app_user_person_active() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.employee_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM employee e WHERE e.employee_id = NEW.employee_id AND e.is_active) THEN
    RAISE EXCEPTION 'Employee % is inactive; an inactive employee cannot have an account', NEW.employee_id
      USING CONSTRAINT = 'rule_account_person_inactive', TABLE = 'app_user';
  END IF;
  IF NEW.patient_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM patient p WHERE p.patient_id = NEW.patient_id AND p.is_active) THEN
    RAISE EXCEPTION 'Patient % is inactive; an inactive patient cannot have an account', NEW.patient_id
      USING CONSTRAINT = 'rule_account_person_inactive', TABLE = 'app_user';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_app_user_before_insert
BEFORE INSERT ON app_user
FOR EACH ROW EXECUTE FUNCTION trg_fn_app_user_person_active();

-- Deactivating an employee or patient locks their account at once (an end date far
-- in the future, which is how ASP.NET Identity represents a permanent lockout);
-- reactivating unlocks it.
CREATE FUNCTION trg_fn_person_lock_account() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_lock timestamptz := CASE WHEN NEW.is_active THEN NULL ELSE TIMESTAMPTZ '9999-12-31 23:59:59+00' END;
BEGIN
  IF NEW.is_active IS DISTINCT FROM OLD.is_active THEN
    IF TG_TABLE_NAME = 'employee' THEN
      UPDATE app_user SET lockout_end = v_lock, lockout_enabled = TRUE WHERE employee_id = NEW.employee_id;
    ELSE
      UPDATE app_user SET lockout_end = v_lock, lockout_enabled = TRUE WHERE patient_id = NEW.patient_id;
    END IF;
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_employee_lock_account
AFTER UPDATE OF is_active ON employee
FOR EACH ROW EXECUTE FUNCTION trg_fn_person_lock_account();

CREATE TRIGGER trg_patient_lock_account
AFTER UPDATE OF is_active ON patient
FOR EACH ROW EXECUTE FUNCTION trg_fn_person_lock_account();

-- =====================================================================
-- 4. Patient scope
-- =====================================================================

-- Patients ask; staff book. Applies to direct inserts and to any change of a booking.
-- The triggers are named trg_<table>_authorize: PostgreSQL fires triggers of the same
-- timing in name order, so these check who is acting before trg_<table>_before_insert
-- and the other rule triggers run.
CREATE FUNCTION trg_fn_patient_cannot_book() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF current_patient_id() IS NOT NULL THEN
    RAISE EXCEPTION 'Patients cannot book or change appointments directly; submit a request instead'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'appointment';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_appointment_authorize
BEFORE INSERT OR UPDATE OR DELETE ON appointment
FOR EACH ROW EXECUTE FUNCTION trg_fn_patient_cannot_book();

-- A patient may submit a request for themselves, and may withdraw it while pending;
-- reviewing it is staff work.
CREATE FUNCTION trg_fn_apptreq_patient_scope() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_patient integer := current_patient_id();
BEGIN
  IF v_patient IS NULL THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  IF TG_OP = 'INSERT' AND NEW.patient_id <> v_patient THEN
    RAISE EXCEPTION 'You can only request appointments for yourself'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'appointment_request';
  ELSIF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'Only clinic staff can review appointment requests'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'appointment_request';
  ELSIF TG_OP = 'DELETE' AND (OLD.patient_id <> v_patient OR OLD.status <> 'Pending') THEN
    RAISE EXCEPTION 'You can only withdraw your own pending requests'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'appointment_request';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_apptreq_authorize
BEFORE INSERT OR UPDATE OR DELETE ON appointment_request
FOR EACH ROW EXECUTE FUNCTION trg_fn_apptreq_patient_scope();

CREATE FUNCTION trg_fn_cancel_patient_scope() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_patient integer := current_patient_id();
BEGIN
  IF v_patient IS NULL THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  IF TG_OP = 'INSERT' AND (NEW.source <> 'Patient' OR NOT EXISTS (
       SELECT 1 FROM appointment a WHERE a.appointment_id = NEW.appointment_id AND a.patient_id = v_patient)) THEN
    RAISE EXCEPTION 'You can only ask to cancel your own appointments'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'cancellation_request';
  ELSIF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'Only clinic staff can review cancellation requests'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'cancellation_request';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_cancel_authorize
BEFORE INSERT OR UPDATE OR DELETE ON cancellation_request
FOR EACH ROW EXECUTE FUNCTION trg_fn_cancel_patient_scope();

-- =====================================================================
-- 5. Audit: record the login as well as the employee
-- =====================================================================
ALTER TABLE audit_log ADD COLUMN changed_by_user integer NULL;
ALTER TABLE audit_log ADD CONSTRAINT fk_audit_user FOREIGN KEY (changed_by_user) REFERENCES app_user (id);

-- Fills the login on every audit row, whichever audit trigger wrote it
CREATE FUNCTION trg_fn_audit_log_user() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.changed_by_user := COALESCE(NEW.changed_by_user, current_user_id());
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_audit_log_user
BEFORE INSERT ON audit_log
FOR EACH ROW EXECUTE FUNCTION trg_fn_audit_log_user();

-- Generic audit for the tables added after the original design: the whole row as
-- JSON. Argument 1 is the primary-key column; argument 2 (optional) a column to omit.
CREATE FUNCTION trg_fn_audit_row() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_old jsonb := CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) END;
  v_new jsonb := CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) END;
BEGIN
  IF TG_NARGS > 1 THEN
    v_old := v_old - TG_ARGV[1];
    v_new := v_new - TG_ARGV[1];
  END IF;
  INSERT INTO audit_log (table_name, record_id, action, changed_by, old_values, new_values)
  VALUES (TG_TABLE_NAME, (COALESCE(v_new, v_old) ->> TG_ARGV[0])::integer, TG_OP::audit_action,
          current_employee_id(), v_old, v_new);
  RETURN NULL;
END;
$$;

COMMENT ON CONSTRAINT uq_app_user_name      ON app_user IS 'That user name is already taken.';
COMMENT ON CONSTRAINT uq_app_user_email     ON app_user IS 'Another account already uses that email address.';
COMMENT ON CONSTRAINT uq_app_user_employee  ON app_user IS 'This employee already has an account.';
COMMENT ON CONSTRAINT uq_app_user_patient   ON app_user IS 'This patient already has an account.';
COMMENT ON CONSTRAINT ck_app_user_one_person ON app_user IS 'An account belongs to exactly one employee or one patient.';
COMMENT ON CONSTRAINT ck_app_user_failed_count ON app_user IS 'The failed sign-in count cannot be negative.';
