-- =====================================================================
-- ClinicScheduler V2: Billing
-- Apply after 04_accounts.sql.
--
-- Contents
--   1. Fees on service_type; invoice, invoice_line, payment and
--      insurance_policy tables
--   2. Invoice rules: lines only while Draft, only for that patient's
--      completed visits, each visit billed once; legal status changes
--   3. Payment rules: only on sent invoices, never over the balance,
--      immutable; paying in full marks the invoice Paid
--   4. Views: invoice totals and balances, patient balances, superbill
--   5. Audit
--
-- Totals are never stored: a line's amount is a generated column and an
-- invoice's total, paid amount and balance come from vw_invoice_summary,
-- so they cannot drift from the rows they are computed from. "Overdue"
-- is likewise computed from the due date rather than kept as a status.
-- =====================================================================

-- =====================================================================
-- 1. Tables
-- =====================================================================
CREATE TYPE invoice_status AS ENUM ('Draft', 'Sent', 'Paid', 'Void');
CREATE TYPE payment_method AS ENUM ('Card', 'Cash', 'Check', 'Insurance');

ALTER TABLE service_type ADD COLUMN fee numeric(10,2) NOT NULL DEFAULT 0;
ALTER TABLE service_type ADD CONSTRAINT ck_service_fee CHECK (fee >= 0);

CREATE TABLE invoice (
  invoice_id  integer        GENERATED BY DEFAULT AS IDENTITY,
  patient_id  integer        NOT NULL,
  status      invoice_status NOT NULL DEFAULT 'Draft',
  created_by  integer        NOT NULL,
  created_at  timestamp      NOT NULL DEFAULT clinic_now(),
  issued_on   date           NULL,
  due_on      date           NULL,
  voided_at   timestamp      NULL,
  void_reason varchar(255)   NULL,
  notes       text           NULL,
  CONSTRAINT pk_invoice PRIMARY KEY (invoice_id),
  CONSTRAINT fk_invoice_patient FOREIGN KEY (patient_id) REFERENCES patient (patient_id),
  CONSTRAINT fk_invoice_created_by FOREIGN KEY (created_by) REFERENCES staff (employee_id),
  -- A draft has not been issued; a sent or paid invoice has an issue and a due date
  CONSTRAINT ck_invoice_issue CHECK (
    (status = 'Draft' AND issued_on IS NULL AND due_on IS NULL) OR
    (status IN ('Sent', 'Paid') AND issued_on IS NOT NULL AND due_on IS NOT NULL) OR
    (status = 'Void')),
  CONSTRAINT ck_invoice_due CHECK (due_on IS NULL OR issued_on IS NULL OR due_on >= issued_on),
  -- Only a void invoice records when and why it was voided, and the why is not blank
  CONSTRAINT ck_invoice_void CHECK (
    (status = 'Void') = (voided_at IS NOT NULL AND COALESCE(length(trim(void_reason)), 0) > 0))
);
CREATE INDEX idx_invoice_patient ON invoice (patient_id, status);

CREATE TABLE invoice_line (
  line_id        integer       GENERATED BY DEFAULT AS IDENTITY,
  invoice_id     integer       NOT NULL,
  appointment_id integer       NULL,
  description    varchar(200)  NOT NULL,
  billing_code   varchar(20)   NULL,
  quantity       smallint      NOT NULL DEFAULT 1,
  unit_price     numeric(10,2) NOT NULL,
  amount         numeric(12,2) NOT NULL GENERATED ALWAYS AS (quantity * unit_price) STORED,
  CONSTRAINT pk_invoice_line PRIMARY KEY (line_id),
  CONSTRAINT fk_line_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (invoice_id) ON DELETE CASCADE,
  CONSTRAINT fk_line_appointment FOREIGN KEY (appointment_id) REFERENCES appointment (appointment_id),
  CONSTRAINT ck_line_quantity CHECK (quantity > 0),
  CONSTRAINT ck_line_price CHECK (unit_price >= 0),
  CONSTRAINT ck_line_description CHECK (length(trim(description)) > 0)
);
CREATE INDEX idx_line_invoice ON invoice_line (invoice_id);
CREATE INDEX idx_line_appointment ON invoice_line (appointment_id);

CREATE TABLE payment (
  payment_id  integer        GENERATED BY DEFAULT AS IDENTITY,
  invoice_id  integer        NOT NULL,
  amount      numeric(10,2)  NOT NULL,
  method      payment_method NOT NULL,
  reference   varchar(60)    NULL,
  paid_at     timestamp      NOT NULL DEFAULT clinic_now(),
  recorded_by integer        NOT NULL,
  CONSTRAINT pk_payment PRIMARY KEY (payment_id),
  CONSTRAINT fk_payment_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (invoice_id),
  CONSTRAINT fk_payment_recorded_by FOREIGN KEY (recorded_by) REFERENCES staff (employee_id),
  CONSTRAINT ck_payment_amount CHECK (amount > 0)
);
CREATE INDEX idx_payment_invoice ON payment (invoice_id);

CREATE TABLE insurance_policy (
  policy_id      integer      GENERATED BY DEFAULT AS IDENTITY,
  patient_id     integer      NOT NULL,
  payer_name     varchar(100) NOT NULL,
  member_id      varchar(40)  NOT NULL,
  group_number   varchar(40)  NULL,
  is_primary     boolean      NOT NULL DEFAULT TRUE,
  effective_from date         NOT NULL,
  effective_to   date         NULL,
  is_active      boolean      NOT NULL DEFAULT TRUE,
  CONSTRAINT pk_insurance_policy PRIMARY KEY (policy_id),
  CONSTRAINT fk_policy_patient FOREIGN KEY (patient_id) REFERENCES patient (patient_id),
  CONSTRAINT uq_policy_member UNIQUE (payer_name, member_id),
  CONSTRAINT ck_policy_dates CHECK (effective_to IS NULL OR effective_to >= effective_from)
);
-- At most one active primary policy per patient
CREATE UNIQUE INDEX uq_policy_one_primary ON insurance_policy (patient_id) WHERE is_primary AND is_active;

-- =====================================================================
-- 2. Invoice rules
-- =====================================================================

-- Lines can only change while their invoice is a draft. A line for a visit must be
-- for that patient's completed visit, and a visit is billed on one live invoice only.
CREATE FUNCTION trg_fn_invoice_line_rules() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_invoice   integer := COALESCE(NEW.invoice_id, OLD.invoice_id);
  v_status    invoice_status;
  v_patient   integer;
  v_appt      record;
  v_billed_on integer;
BEGIN
  -- Lock the invoice so a line cannot slip in while it is being sent
  SELECT i.status, i.patient_id INTO v_status, v_patient
    FROM invoice i WHERE i.invoice_id = v_invoice FOR UPDATE;
  IF NOT FOUND THEN
    -- The invoice itself is being deleted (cascade); its own trigger already allowed it
    RETURN COALESCE(NEW, OLD);
  END IF;
  IF v_status <> 'Draft' THEN
    RAISE EXCEPTION 'Invoice % is %; lines can only change while it is a draft', v_invoice, v_status
      USING CONSTRAINT = 'rule_invoice_not_draft', TABLE = 'invoice_line';
  END IF;

  IF TG_OP <> 'DELETE' AND NEW.appointment_id IS NOT NULL THEN
    -- Lock the visit so two invoices cannot bill it at the same moment
    SELECT a.patient_id, a.status INTO v_appt
      FROM appointment a WHERE a.appointment_id = NEW.appointment_id FOR UPDATE;
    IF NOT FOUND THEN
      RETURN NEW; -- let the foreign key report it
    END IF;
    IF v_appt.patient_id <> v_patient THEN
      RAISE EXCEPTION 'Appointment % is not for this invoice''s patient', NEW.appointment_id
        USING CONSTRAINT = 'rule_line_wrong_patient', TABLE = 'invoice_line';
    END IF;
    IF v_appt.status <> 'Completed' THEN
      RAISE EXCEPTION 'Appointment % is %; only completed visits can be billed', NEW.appointment_id, v_appt.status
        USING CONSTRAINT = 'rule_line_not_completed', TABLE = 'invoice_line';
    END IF;
    SELECT l.invoice_id INTO v_billed_on
      FROM invoice_line l JOIN invoice i ON i.invoice_id = l.invoice_id
      WHERE l.appointment_id = NEW.appointment_id AND i.status <> 'Void'
        AND l.line_id IS DISTINCT FROM NEW.line_id
      LIMIT 1;
    IF v_billed_on IS NOT NULL THEN
      RAISE EXCEPTION 'Appointment % is already billed on invoice %', NEW.appointment_id, v_billed_on
        USING CONSTRAINT = 'rule_appointment_already_billed', TABLE = 'invoice_line';
    END IF;
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_invoice_line_rules
BEFORE INSERT OR UPDATE OR DELETE ON invoice_line
FOR EACH ROW EXECUTE FUNCTION trg_fn_invoice_line_rules();

-- Allowed status changes:
--   Draft -> Sent   needs at least one line and a total above zero; stamps the dates
--   Draft -> Void, Sent -> Void   needs a reason; a sent invoice only while unpaid
--   Sent  -> Paid   only when payments cover the total (the payment trigger does this)
--   Paid and Void are final
CREATE FUNCTION trg_fn_invoice_rules() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_total numeric;
  v_paid  numeric;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'Draft' THEN
      RAISE EXCEPTION 'Invoice % is %; only a draft can be deleted (void it instead)', OLD.invoice_id, OLD.status
        USING CONSTRAINT = 'rule_invoice_delete_draft_only', TABLE = 'invoice';
    END IF;
    RETURN OLD;
  END IF;

  IF NEW.patient_id <> OLD.patient_id THEN
    RAISE EXCEPTION 'An invoice cannot move to another patient'
      USING CONSTRAINT = 'rule_invoice_patient_fixed', TABLE = 'invoice';
  END IF;

  IF NEW.status = OLD.status THEN
    IF OLD.status IN ('Paid', 'Void') THEN
      RAISE EXCEPTION 'Invoice % is % and can no longer change', OLD.invoice_id, OLD.status
        USING CONSTRAINT = 'rule_invoice_closed', TABLE = 'invoice';
    END IF;
    RETURN NEW;
  END IF;

  SELECT COALESCE(SUM(l.amount), 0) INTO v_total FROM invoice_line l WHERE l.invoice_id = NEW.invoice_id;
  SELECT COALESCE(SUM(p.amount), 0) INTO v_paid  FROM payment p      WHERE p.invoice_id = NEW.invoice_id;

  IF OLD.status IN ('Paid', 'Void') THEN
    RAISE EXCEPTION 'Invoice % is % and can no longer change', OLD.invoice_id, OLD.status
      USING CONSTRAINT = 'rule_invoice_closed', TABLE = 'invoice';
  ELSIF OLD.status = 'Draft' AND NEW.status = 'Sent' THEN
    IF v_total <= 0 THEN
      RAISE EXCEPTION 'Invoice % has nothing to bill; add a line before sending it', NEW.invoice_id
        USING CONSTRAINT = 'rule_invoice_empty', TABLE = 'invoice';
    END IF;
    NEW.issued_on := COALESCE(NEW.issued_on, clinic_now()::date);
    NEW.due_on    := COALESCE(NEW.due_on, NEW.issued_on + 30);
  ELSIF NEW.status = 'Void' THEN
    IF v_paid > 0 THEN
      RAISE EXCEPTION 'Invoice % has payments recorded and cannot be voided', NEW.invoice_id
        USING CONSTRAINT = 'rule_invoice_has_payments', TABLE = 'invoice';
    END IF;
    NEW.voided_at := COALESCE(NEW.voided_at, clinic_now());
  ELSIF OLD.status = 'Sent' AND NEW.status = 'Paid' THEN
    IF v_paid < v_total THEN
      RAISE EXCEPTION 'Invoice % still has % due; it is marked paid when payments cover it', NEW.invoice_id, v_total - v_paid
        USING CONSTRAINT = 'rule_invoice_balance_due', TABLE = 'invoice';
    END IF;
  ELSE
    RAISE EXCEPTION 'An invoice cannot go from % to %', OLD.status, NEW.status
      USING CONSTRAINT = 'rule_invoice_transition', TABLE = 'invoice';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_invoice_rules
BEFORE UPDATE OR DELETE ON invoice
FOR EACH ROW EXECUTE FUNCTION trg_fn_invoice_rules();

-- A new invoice always starts as a draft
CREATE FUNCTION trg_fn_invoice_new_draft() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status <> 'Draft' THEN
    RAISE EXCEPTION 'A new invoice starts as a draft'
      USING CONSTRAINT = 'rule_invoice_transition', TABLE = 'invoice';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_invoice_before_insert
BEFORE INSERT ON invoice
FOR EACH ROW EXECUTE FUNCTION trg_fn_invoice_new_draft();

-- =====================================================================
-- 3. Payment rules
-- =====================================================================
CREATE FUNCTION trg_fn_payment_rules() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_status invoice_status;
  v_total  numeric;
  v_paid   numeric;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'Payments cannot be changed or deleted once recorded'
      USING CONSTRAINT = 'rule_payment_immutable', TABLE = 'payment';
  END IF;

  -- Lock the invoice so two payments cannot both fit under the same balance
  SELECT i.status INTO v_status FROM invoice i WHERE i.invoice_id = NEW.invoice_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN NEW; -- let the foreign key report it
  END IF;
  IF v_status <> 'Sent' THEN
    RAISE EXCEPTION 'Invoice % is %; payments can only be recorded on a sent invoice', NEW.invoice_id, v_status
      USING CONSTRAINT = 'rule_payment_invoice_not_open', TABLE = 'payment';
  END IF;

  SELECT COALESCE(SUM(l.amount), 0) INTO v_total FROM invoice_line l WHERE l.invoice_id = NEW.invoice_id;
  SELECT COALESCE(SUM(p.amount), 0) INTO v_paid  FROM payment p      WHERE p.invoice_id = NEW.invoice_id;
  IF NEW.amount > v_total - v_paid THEN
    RAISE EXCEPTION 'Payment of % is more than the % still due on invoice %', NEW.amount, v_total - v_paid, NEW.invoice_id
      USING CONSTRAINT = 'rule_payment_exceeds_balance', TABLE = 'payment';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_payment_rules
BEFORE INSERT OR UPDATE OR DELETE ON payment
FOR EACH ROW EXECUTE FUNCTION trg_fn_payment_rules();

-- Paying the balance in full marks the invoice paid
CREATE FUNCTION trg_fn_payment_settle() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  UPDATE invoice i SET status = 'Paid'
  WHERE i.invoice_id = NEW.invoice_id AND i.status = 'Sent'
    AND (SELECT COALESCE(SUM(p.amount), 0) FROM payment p WHERE p.invoice_id = i.invoice_id)
     >= (SELECT COALESCE(SUM(l.amount), 0) FROM invoice_line l WHERE l.invoice_id = i.invoice_id);
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_payment_settle
AFTER INSERT ON payment
FOR EACH ROW EXECUTE FUNCTION trg_fn_payment_settle();

-- =====================================================================
-- 4. Views
-- =====================================================================
CREATE VIEW vw_invoice_summary AS
SELECT i.invoice_id,
       i.patient_id,
       p.first_name || ' ' || p.last_name AS patient,
       i.status,
       i.created_at,
       i.issued_on,
       i.due_on,
       COALESCE(l.total, 0)                      AS total,
       COALESCE(pay.paid, 0)                     AS paid,
       CASE WHEN i.status = 'Void' THEN 0
            ELSE COALESCE(l.total, 0) - COALESCE(pay.paid, 0) END AS balance,
       (i.status = 'Sent' AND i.due_on < clinic_now()::date) AS is_overdue,
       COALESCE(l.line_count, 0)                 AS line_count
FROM invoice i
JOIN patient p ON p.patient_id = i.patient_id
LEFT JOIN (SELECT invoice_id, SUM(amount) AS total, COUNT(*) AS line_count
           FROM invoice_line GROUP BY invoice_id) l ON l.invoice_id = i.invoice_id
LEFT JOIN (SELECT invoice_id, SUM(amount) AS paid
           FROM payment GROUP BY invoice_id) pay ON pay.invoice_id = i.invoice_id;

-- What each patient owes on invoices that have been sent
CREATE VIEW vw_patient_balance AS
SELECT p.patient_id,
       p.first_name || ' ' || p.last_name AS patient,
       COALESCE(SUM(s.balance) FILTER (WHERE s.status = 'Sent'), 0) AS open_balance,
       COALESCE(SUM(s.balance) FILTER (WHERE s.is_overdue), 0)       AS overdue_balance
FROM patient p
LEFT JOIN vw_invoice_summary s ON s.patient_id = p.patient_id
GROUP BY p.patient_id, p.first_name, p.last_name;

-- One superbill line per billed visit: what an insurer needs to reimburse the patient
CREATE VIEW vw_superbill AS
SELECT l.invoice_id,
       l.line_id,
       p.patient_id,
       p.first_name || ' ' || p.last_name AS patient,
       p.date_of_birth,
       ip.payer_name,
       ip.member_id,
       ip.group_number,
       e.first_name || ' ' || e.last_name AS provider,
       pr.credential,
       pr.npi,
       a.start_time::date                 AS service_date,
       st.name                            AS service,
       l.billing_code,
       l.description,
       l.quantity,
       l.unit_price,
       l.amount,
       loc.name                           AS location,
       loc.street || ', ' || loc.city || ', ' || loc.state || ' ' || loc.zip AS location_address
FROM invoice_line l
JOIN invoice i          ON i.invoice_id       = l.invoice_id
JOIN appointment a      ON a.appointment_id   = l.appointment_id
JOIN patient p          ON p.patient_id       = i.patient_id
JOIN provider pr        ON pr.employee_id     = a.provider_id
JOIN employee e         ON e.employee_id      = pr.employee_id
JOIN service_type st    ON st.service_type_id = a.service_type_id
JOIN room r             ON r.room_id          = a.room_id
JOIN location loc       ON loc.location_id    = r.location_id
LEFT JOIN insurance_policy ip ON ip.patient_id = p.patient_id AND ip.is_primary AND ip.is_active
WHERE i.status <> 'Void';

