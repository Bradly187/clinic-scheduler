COMMENT ON CONSTRAINT ck_waitlist_dates  ON waitlist_entry IS 'The latest date cannot be before the earliest date.';
COMMENT ON CONSTRAINT ck_waitlist_booked ON waitlist_entry IS 'A booked waitlist entry must name its appointment, and only a booked one does.';
