-- Bookings, reschedules and cancellations, told to the patient and the provider
CREATE FUNCTION trg_fn_appointment_notify() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_visit    text := fn_visit_text(NEW.appointment_id);
  v_location integer;
  v_waiting  text;
  v_count    integer;
BEGIN
  IF TG_OP = 'INSERT' AND NEW.status = 'Scheduled' THEN
    IF NEW.rescheduled_from_id IS NOT NULL THEN
      INSERT INTO notification (recipient_patient_id, kind, title, body, appointment_id)
      VALUES (NEW.patient_id, 'AppointmentRescheduled', 'Missed visit rescheduled',
              'We booked you a new visit: ' || v_visit || '.', NEW.appointment_id);
    ELSE
      INSERT INTO notification (recipient_patient_id, kind, title, body, appointment_id)
      VALUES (NEW.patient_id, 'AppointmentBooked', 'Appointment booked',
              'You are booked for ' || v_visit || '.', NEW.appointment_id);
    END IF;
    INSERT INTO notification (recipient_employee_id, kind, title, body, appointment_id)
    SELECT NEW.provider_id, 'AppointmentBooked', 'New visit on your schedule',
           p.first_name || ' ' || p.last_name || ': ' || v_visit || '.', NEW.appointment_id
    FROM patient p WHERE p.patient_id = NEW.patient_id;

  ELSIF TG_OP = 'UPDATE' AND OLD.status = 'Scheduled' AND NEW.status = 'Canceled' THEN
    INSERT INTO notification (recipient_patient_id, kind, title, body, appointment_id)
    VALUES (NEW.patient_id, 'AppointmentCanceled', 'Appointment canceled',
            'Your visit was canceled: ' || v_visit || '.', NEW.appointment_id);
    INSERT INTO notification (recipient_employee_id, kind, title, body, appointment_id)
    SELECT NEW.provider_id, 'AppointmentCanceled', 'Visit canceled',
           p.first_name || ' ' || p.last_name || ': ' || v_visit || '.', NEW.appointment_id
    FROM patient p WHERE p.patient_id = NEW.patient_id;

    -- A future slot opened: tell the location's staff, and anyone waiting who could take it
    IF NEW.start_time > clinic_now() THEN
      SELECT r.location_id INTO v_location FROM room r WHERE r.room_id = NEW.room_id;
      SELECT string_agg(p.first_name || ' ' || p.last_name, ', ' ORDER BY w.created_at), COUNT(*)
        INTO v_waiting, v_count
        FROM waitlist_entry w JOIN patient p ON p.patient_id = w.patient_id
        WHERE w.status = 'Waiting' AND w.service_type_id = NEW.service_type_id
          AND w.patient_id <> NEW.patient_id
          AND NEW.start_time::date BETWEEN w.earliest_date AND w.latest_date
          AND (w.preferred_location_id IS NULL OR w.preferred_location_id = v_location)
          AND (w.preferred_provider_id IS NULL OR w.preferred_provider_id = NEW.provider_id);
      IF v_count > 0 THEN
        PERFORM fn_notify_location_staff(v_location, 'WaitlistSlotOpened', 'Slot opened for the waitlist',
          'A canceled visit freed ' || v_visit || '. Waiting: ' || v_waiting || '.', NEW.appointment_id);
        INSERT INTO notification (recipient_patient_id, kind, title, body, appointment_id)
        SELECT w.patient_id, 'WaitlistSlotOpened', 'An opening may suit you',
               'A slot opened: ' || v_visit || '. Call the clinic to take it.', NEW.appointment_id
        FROM waitlist_entry w
        WHERE w.status = 'Waiting' AND w.service_type_id = NEW.service_type_id
          AND w.patient_id <> NEW.patient_id
          AND NEW.start_time::date BETWEEN w.earliest_date AND w.latest_date
          AND (w.preferred_location_id IS NULL OR w.preferred_location_id = v_location)
          AND (w.preferred_provider_id IS NULL OR w.preferred_provider_id = NEW.provider_id);
      END IF;
    END IF;
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_appointment_notify
AFTER INSERT OR UPDATE OF status ON appointment
FOR EACH ROW EXECUTE FUNCTION trg_fn_appointment_notify();

-- Requests: staff hear about new ones; patients hear the decision
CREATE FUNCTION trg_fn_apptreq_notify() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_name    text;
  v_service text;
BEGIN
  SELECT p.first_name || ' ' || p.last_name INTO v_name FROM patient p WHERE p.patient_id = NEW.patient_id;
  SELECT s.name INTO v_service FROM service_type s WHERE s.service_type_id = NEW.service_type_id;

  IF TG_OP = 'INSERT' AND NEW.status = 'Pending' THEN
    PERFORM fn_notify_location_staff(NEW.preferred_location_id, 'RequestSubmitted', 'New appointment request',
      v_name || ' asked for a ' || lower(v_service) || ' around '
      || to_char(NEW.preferred_start, 'Dy Mon FMDD "at" FMHH12:MI AM') || '.');
  ELSIF TG_OP = 'UPDATE' AND OLD.status = 'Pending' AND NEW.status = 'Approved' THEN
    -- Turn the booking notice the new appointment just produced into the approval
    UPDATE notification SET kind = 'RequestApproved', title = 'Request approved'
    WHERE appointment_id = NEW.appointment_id AND recipient_patient_id = NEW.patient_id
      AND kind = 'AppointmentBooked';
  ELSIF TG_OP = 'UPDATE' AND OLD.status = 'Pending' AND NEW.status = 'Denied' THEN
    INSERT INTO notification (recipient_patient_id, kind, title, body)
    VALUES (NEW.patient_id, 'RequestDenied', 'Request not approved',
            'Your request for a ' || lower(v_service) || ' was not approved'
            || COALESCE(': ' || NEW.decision_note, '') || '.');
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_apptreq_notify
AFTER INSERT OR UPDATE OF status ON appointment_request
FOR EACH ROW EXECUTE FUNCTION trg_fn_apptreq_notify();

-- Cancellation requests: staff hear about new ones; patients hear a denial
-- (an approval cancels the visit, which notifies them already)
CREATE FUNCTION trg_fn_cancel_notify() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_patient  integer;
  v_location integer;
BEGIN
  SELECT a.patient_id, r.location_id INTO v_patient, v_location
    FROM appointment a JOIN room r ON r.room_id = a.room_id
    WHERE a.appointment_id = NEW.appointment_id;

  IF TG_OP = 'INSERT' AND NEW.status = 'Pending' THEN
    PERFORM fn_notify_location_staff(v_location, 'CancellationRequested', 'Cancellation requested',
      (SELECT p.first_name || ' ' || p.last_name FROM patient p WHERE p.patient_id = v_patient)
      || ' asked to cancel ' || fn_visit_text(NEW.appointment_id) || ': ' || NEW.reason || '.',
      NEW.appointment_id);
  ELSIF TG_OP = 'UPDATE' AND OLD.status = 'Pending' AND NEW.status = 'Denied' THEN
    INSERT INTO notification (recipient_patient_id, kind, title, body, appointment_id)
    VALUES (v_patient, 'CancellationDenied', 'Your visit is still on',
            'We could not cancel ' || fn_visit_text(NEW.appointment_id) || '. Please call the clinic.',
            NEW.appointment_id);
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_cancel_notify
AFTER INSERT OR UPDATE OF status ON cancellation_request
FOR EACH ROW EXECUTE FUNCTION trg_fn_cancel_notify();

-- Invoices: the patient hears when one is sent
CREATE FUNCTION trg_fn_invoice_notify() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.status = 'Draft' AND NEW.status = 'Sent' THEN
    INSERT INTO notification (recipient_patient_id, kind, title, body, invoice_id)
    SELECT NEW.patient_id, 'InvoiceSent', 'New invoice',
           'Invoice #' || NEW.invoice_id || ' for $' || to_char(s.total, 'FM999,990.00')
           || ' is due ' || to_char(NEW.due_on, 'Mon FMDD, YYYY') || '.', NEW.invoice_id
    FROM vw_invoice_summary s WHERE s.invoice_id = NEW.invoice_id;
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_invoice_notify
AFTER UPDATE OF status ON invoice
FOR EACH ROW EXECUTE FUNCTION trg_fn_invoice_notify();

-- =====================================================================
-- 5. Booking into any free room
-- =====================================================================

-- Books a visit at a location, trying each active room of the type the service
-- needs until the scheduling rules accept one. Errors that no other room would fix
-- (provider or patient already booked, clinic hours, qualification) are raised
-- straight away; if every room is full, says so. Returns the new appointment_id.
CREATE FUNCTION sp_book_appointment(
  p_patient    integer,
  p_provider   integer,
  p_service    integer,
  p_location   integer,
  p_start      timestamp,
  p_end        timestamp,
  p_created_by integer,
  p_notes      text DEFAULT NULL,
  p_plan_item  integer DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
  v_room_type  room_type;
  v_room       integer;
  v_new_id     integer;
  v_constraint text;
  v_message    text;
  v_rooms      integer := 0;
BEGIN
  SELECT s.required_room_type INTO v_room_type FROM service_type s WHERE s.service_type_id = p_service;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Service % does not exist', p_service
      USING CONSTRAINT = 'rule_service_not_found', TABLE = 'appointment';
  END IF;

  FOR v_room IN
    SELECT r.room_id FROM room r
    WHERE r.location_id = p_location AND r.room_type = v_room_type AND r.is_active
    ORDER BY r.room_id
  LOOP
    v_rooms := v_rooms + 1;
    BEGIN
      INSERT INTO appointment (patient_id, provider_id, room_id, service_type_id, plan_item_id,
                               created_by, start_time, end_time, notes)
      VALUES (p_patient, p_provider, v_room, p_service, p_plan_item,
              p_created_by, p_start, p_end, p_notes)
      RETURNING appointment_id INTO v_new_id;
      RETURN v_new_id;
    EXCEPTION
      WHEN raise_exception THEN
        GET STACKED DIAGNOSTICS v_constraint = CONSTRAINT_NAME, v_message = MESSAGE_TEXT;
        IF v_constraint NOT IN ('rule_room_full', 'rule_room_inactive') THEN
          RAISE EXCEPTION '%', v_message USING CONSTRAINT = v_constraint, TABLE = 'appointment';
        END IF;
    END;
  END LOOP;

  IF v_rooms = 0 THEN
    RAISE EXCEPTION 'Location % has no % room in service', p_location, lower(v_room_type::text)
      USING CONSTRAINT = 'rule_no_room_available', TABLE = 'appointment';
  END IF;
  RAISE EXCEPTION 'Every % room at location % is full at that time', lower(v_room_type::text), p_location
    USING CONSTRAINT = 'rule_no_room_available', TABLE = 'appointment';
END;
$$;

