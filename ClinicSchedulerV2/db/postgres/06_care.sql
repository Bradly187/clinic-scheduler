-- =====================================================================
-- ClinicScheduler V2: Waitlist, visit notes, notifications and booking
-- Apply after 05_billing.sql.
--
-- Contents
--   1. waitlist_entry: one waiting entry per patient and service
--   2. visit_note: written by the visit's provider; signed notes are final
--   3. notification: rows written only by the triggers in this script;
--      readers can only mark their own read
--   4. Notification triggers: bookings, cancellations, request decisions,
--      invoices sent, and freed slots that match the waitlist
--   5. sp_book_appointment: books into the first room at a location that
--      every scheduling rule accepts
--   6. Audit
-- =====================================================================

-- =====================================================================
-- 1. Waitlist
-- =====================================================================
CREATE TYPE waitlist_status AS ENUM ('Waiting', 'Booked', 'Removed');

CREATE TABLE waitlist_entry (
  entry_id              integer         GENERATED BY DEFAULT AS IDENTITY,
  patient_id            integer         NOT NULL,
  service_type_id       integer         NOT NULL,
  preferred_location_id integer         NULL,
  preferred_provider_id integer         NULL,
  earliest_date         date            NOT NULL,
  latest_date           date            NOT NULL,
  notes                 text            NULL,
  status                waitlist_status NOT NULL DEFAULT 'Waiting',
  appointment_id        integer         NULL,
  created_at            timestamp       NOT NULL DEFAULT clinic_now(),
  CONSTRAINT pk_waitlist_entry PRIMARY KEY (entry_id),
  CONSTRAINT fk_waitlist_patient FOREIGN KEY (patient_id) REFERENCES patient (patient_id),
  CONSTRAINT fk_waitlist_service FOREIGN KEY (service_type_id) REFERENCES service_type (service_type_id),
  CONSTRAINT fk_waitlist_location FOREIGN KEY (preferred_location_id) REFERENCES location (location_id),
  CONSTRAINT fk_waitlist_provider FOREIGN KEY (preferred_provider_id) REFERENCES provider (employee_id),
  CONSTRAINT fk_waitlist_appointment FOREIGN KEY (appointment_id) REFERENCES appointment (appointment_id),
  CONSTRAINT ck_waitlist_dates CHECK (latest_date >= earliest_date),
  -- A booked entry names the appointment it became; no other entry does
  CONSTRAINT ck_waitlist_booked CHECK ((status = 'Booked') = (appointment_id IS NOT NULL))
);
-- One waiting entry per patient per service
CREATE UNIQUE INDEX uq_waitlist_one_waiting ON waitlist_entry (patient_id, service_type_id) WHERE status = 'Waiting';
CREATE INDEX idx_waitlist_match ON waitlist_entry (service_type_id, status, earliest_date);

CREATE FUNCTION trg_fn_waitlist_rules() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_patient integer := current_patient_id();
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF v_patient IS NOT NULL THEN
      RAISE EXCEPTION 'Leave the waitlist instead of deleting the entry'
        USING CONSTRAINT = 'rule_patient_scope', TABLE = 'waitlist_entry';
    END IF;
    RETURN OLD;
  END IF;

  -- A patient manages only their own entries, and only while they are waiting
  IF v_patient IS NOT NULL THEN
    IF NEW.patient_id <> v_patient OR (TG_OP = 'UPDATE' AND OLD.patient_id <> v_patient) THEN
      RAISE EXCEPTION 'You can only manage your own waitlist entries'
        USING CONSTRAINT = 'rule_patient_scope', TABLE = 'waitlist_entry';
    END IF;
    IF NEW.status = 'Booked' THEN
      RAISE EXCEPTION 'Only clinic staff can book a waitlist entry'
        USING CONSTRAINT = 'rule_patient_scope', TABLE = 'waitlist_entry';
    END IF;
  END IF;

  IF TG_OP = 'UPDATE' AND OLD.status <> 'Waiting' AND NEW.status IS DISTINCT FROM OLD.status THEN
    RAISE EXCEPTION 'Waitlist entry % is already %', OLD.entry_id, OLD.status
      USING CONSTRAINT = 'rule_waitlist_closed', TABLE = 'waitlist_entry';
  END IF;

  IF TG_OP = 'INSERT' AND NEW.latest_date < clinic_now()::date THEN
    RAISE EXCEPTION 'The waitlist window has already passed'
      USING CONSTRAINT = 'rule_waitlist_window_past', TABLE = 'waitlist_entry';
  END IF;

  -- The booked appointment must be this patient's, for this service
  IF NEW.appointment_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM appointment a
       WHERE a.appointment_id = NEW.appointment_id
         AND a.patient_id = NEW.patient_id AND a.service_type_id = NEW.service_type_id) THEN
    RAISE EXCEPTION 'Appointment % is not this patient''s % visit', NEW.appointment_id,
                    (SELECT s.name FROM service_type s WHERE s.service_type_id = NEW.service_type_id)
      USING CONSTRAINT = 'rule_waitlist_wrong_appointment', TABLE = 'waitlist_entry';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_waitlist_rules
BEFORE INSERT OR UPDATE OR DELETE ON waitlist_entry
FOR EACH ROW EXECUTE FUNCTION trg_fn_waitlist_rules();

-- =====================================================================
-- 2. Visit notes
-- =====================================================================
CREATE TABLE visit_note (
  note_id        integer   GENERATED BY DEFAULT AS IDENTITY,
  appointment_id integer   NOT NULL,
  author_id      integer   NOT NULL,
  body           text      NOT NULL,
  created_at     timestamp NOT NULL DEFAULT clinic_now(),
  updated_at     timestamp NULL,
  signed_at      timestamp NULL,
  CONSTRAINT pk_visit_note PRIMARY KEY (note_id),
  CONSTRAINT fk_note_appointment FOREIGN KEY (appointment_id) REFERENCES appointment (appointment_id),
  CONSTRAINT fk_note_author FOREIGN KEY (author_id) REFERENCES provider (employee_id),
  CONSTRAINT ck_note_body CHECK (length(trim(body)) > 0)
);
CREATE INDEX idx_note_appointment ON visit_note (appointment_id);

CREATE FUNCTION trg_fn_visit_note_rules() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_actor  integer := current_employee_id();
  v_appt   record;
BEGIN
  IF current_patient_id() IS NOT NULL THEN
    RAISE EXCEPTION 'Patients cannot write visit notes'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'visit_note';
  END IF;

  -- A signed note is part of the record: it can be neither edited nor deleted
  IF TG_OP IN ('UPDATE', 'DELETE') AND OLD.signed_at IS NOT NULL THEN
    RAISE EXCEPTION 'Note % was signed and can no longer change; add a new note instead', OLD.note_id
      USING CONSTRAINT = 'rule_note_signed', TABLE = 'visit_note';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF v_actor IS NOT NULL AND v_actor <> OLD.author_id THEN
      RAISE EXCEPTION 'Only the note''s author can delete it'
        USING CONSTRAINT = 'rule_note_wrong_author', TABLE = 'visit_note';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'UPDATE' AND (NEW.appointment_id <> OLD.appointment_id OR NEW.author_id <> OLD.author_id) THEN
    RAISE EXCEPTION 'A note cannot move to another visit or author'
      USING CONSTRAINT = 'rule_note_wrong_author', TABLE = 'visit_note';
  END IF;

  SELECT a.provider_id, a.status INTO v_appt FROM appointment a WHERE a.appointment_id = NEW.appointment_id;
  IF NOT FOUND THEN
    RETURN NEW; -- let the foreign key report it
  END IF;
  IF NEW.author_id <> v_appt.provider_id THEN
    RAISE EXCEPTION 'Only the visit''s provider can write its notes'
      USING CONSTRAINT = 'rule_note_wrong_author', TABLE = 'visit_note';
  END IF;
  -- When the session names an employee, it must be the author
  IF v_actor IS NOT NULL AND v_actor <> NEW.author_id THEN
    RAISE EXCEPTION 'Notes are written in the author''s own name'
      USING CONSTRAINT = 'rule_note_wrong_author', TABLE = 'visit_note';
  END IF;
  IF v_appt.status = 'Canceled' THEN
    RAISE EXCEPTION 'Appointment % was canceled; there is no visit to document', NEW.appointment_id
      USING CONSTRAINT = 'rule_note_canceled_visit', TABLE = 'visit_note';
  END IF;
  IF NEW.signed_at IS NOT NULL AND v_appt.status <> 'Completed' THEN
    RAISE EXCEPTION 'A note can only be signed once the visit is completed'
      USING CONSTRAINT = 'rule_note_sign_incomplete', TABLE = 'visit_note';
  END IF;

  IF TG_OP = 'UPDATE' THEN
    NEW.updated_at := clinic_now();
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_visit_note_rules
BEFORE INSERT OR UPDATE OR DELETE ON visit_note
FOR EACH ROW EXECUTE FUNCTION trg_fn_visit_note_rules();

-- =====================================================================
-- 3. Notifications
-- =====================================================================
CREATE TYPE notification_kind AS ENUM (
  'AppointmentBooked', 'AppointmentCanceled', 'AppointmentRescheduled',
  'RequestSubmitted', 'RequestApproved', 'RequestDenied',
  'CancellationRequested', 'CancellationDenied',
  'InvoiceSent', 'WaitlistSlotOpened');

CREATE TABLE notification (
  notification_id       integer           GENERATED BY DEFAULT AS IDENTITY,
  recipient_employee_id integer           NULL,
  recipient_patient_id  integer           NULL,
  kind                  notification_kind NOT NULL,
  title                 varchar(120)      NOT NULL,
  body                  text              NOT NULL,
  appointment_id        integer           NULL,
  invoice_id            integer           NULL,
  created_at            timestamp         NOT NULL DEFAULT clinic_now(),
  read_at               timestamp         NULL,
  CONSTRAINT pk_notification PRIMARY KEY (notification_id),
  CONSTRAINT fk_notification_employee FOREIGN KEY (recipient_employee_id) REFERENCES employee (employee_id),
  CONSTRAINT fk_notification_patient FOREIGN KEY (recipient_patient_id) REFERENCES patient (patient_id),
  CONSTRAINT fk_notification_appointment FOREIGN KEY (appointment_id) REFERENCES appointment (appointment_id),
  CONSTRAINT fk_notification_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (invoice_id),
  -- Every notification goes to exactly one person
  CONSTRAINT ck_notification_recipient CHECK (num_nonnulls(recipient_employee_id, recipient_patient_id) = 1)
);
CREATE INDEX idx_notification_patient  ON notification (recipient_patient_id, read_at);
CREATE INDEX idx_notification_employee ON notification (recipient_employee_id, read_at);

-- Notifications are written only by the database's own triggers (pg_trigger_depth()
-- is above 1 when a trigger's statement fires this one). Clients may only mark their
-- own notifications read; the content is fixed.
CREATE FUNCTION trg_fn_notification_rules() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_patient  integer := current_patient_id();
  v_employee integer := current_employee_id();
BEGIN
  IF pg_trigger_depth() > 1 THEN
    RETURN COALESCE(NEW, OLD);
  END IF;
  IF TG_OP = 'INSERT' THEN
    RAISE EXCEPTION 'Notifications are created by the database, not written directly'
      USING CONSTRAINT = 'rule_notification_fixed', TABLE = 'notification';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Notifications are kept; mark them read instead'
      USING CONSTRAINT = 'rule_notification_fixed', TABLE = 'notification';
  END IF;
  IF (NEW.recipient_employee_id, NEW.recipient_patient_id, NEW.kind, NEW.title, NEW.body,
      NEW.appointment_id, NEW.invoice_id, NEW.created_at)
     IS DISTINCT FROM
     (OLD.recipient_employee_id, OLD.recipient_patient_id, OLD.kind, OLD.title, OLD.body,
      OLD.appointment_id, OLD.invoice_id, OLD.created_at) THEN
    RAISE EXCEPTION 'Only the read time of a notification can change'
      USING CONSTRAINT = 'rule_notification_fixed', TABLE = 'notification';
  END IF;
  IF (v_patient IS NOT NULL AND OLD.recipient_patient_id IS DISTINCT FROM v_patient)
     OR (v_patient IS NULL AND v_employee IS NOT NULL AND OLD.recipient_employee_id IS DISTINCT FROM v_employee) THEN
    RAISE EXCEPTION 'You can only mark your own notifications read'
      USING CONSTRAINT = 'rule_patient_scope', TABLE = 'notification';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_notification_rules
BEFORE INSERT OR UPDATE OR DELETE ON notification
FOR EACH ROW EXECUTE FUNCTION trg_fn_notification_rules();

-- Readable description of a visit, used in notification text
CREATE FUNCTION fn_visit_text(p_appointment_id integer) RETURNS text
LANGUAGE sql STABLE
AS $$
  SELECT st.name || ' on ' || to_char(a.start_time, 'Dy Mon FMDD "at" FMHH12:MI AM')
         || ' with ' || e.first_name || ' ' || e.last_name || ', ' || pr.credential
         || ' at ' || replace(l.name, 'Houston Arthritis Center - ', '')
  FROM appointment a
  JOIN service_type st ON st.service_type_id = a.service_type_id
  JOIN provider pr     ON pr.employee_id     = a.provider_id
  JOIN employee e      ON e.employee_id      = pr.employee_id
  JOIN room r          ON r.room_id          = a.room_id
  JOIN location l      ON l.location_id      = r.location_id
  WHERE a.appointment_id = p_appointment_id
$$;

-- Notify every active staff member who works at a location
CREATE FUNCTION fn_notify_location_staff(
  p_location integer, p_kind notification_kind, p_title text, p_body text,
  p_appointment integer DEFAULT NULL)
RETURNS void
LANGUAGE sql
AS $$
  INSERT INTO notification (recipient_employee_id, kind, title, body, appointment_id)
  SELECT s.employee_id, p_kind, p_title, p_body, p_appointment
  FROM staff s
  JOIN employee e           ON e.employee_id = s.employee_id AND e.is_active
  JOIN employee_location el ON el.employee_id = s.employee_id
  WHERE p_location IS NULL OR el.location_id = p_location
  GROUP BY s.employee_id
$$;

